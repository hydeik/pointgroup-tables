AXIAL_FAMILIES = ("Cn", "Cnv", "Cnh", "S2n", "Dn", "Dnd", "Dnh")
POLYHEDRAL = ("T", "Td", "Th", "O", "Oh", "I", "Ih")
# families whose rotation group is cyclic: their double groups are abelian, so
# every irrep (ordinary and projective) is one-dimensional and a chain ends
TERMINAL_FAMILIES = ("Cn", "Cnh", "S2n")
# families whose point group is abelian (ordinary irreps one-dimensional)
ABELIAN_SYMBOLS = {"D2", "C2v", "D2h", "C2h"}

Subgroup = frozenset[int]


# ---- subgroups --------------------------------------------------------------------


def closure(table: list[list[int]], generators: list[int]) -> Subgroup:
    """The subgroup generated by ``generators`` (element indices), from the identity."""
    members = {0}
    frontier = [0]
    while frontier:
        following = []
        for x in frontier:
            for g in generators:
                y = table[x][g]
                if y not in members:
                    members.add(y)
                    following.append(y)
        frontier = following
    return frozenset(members)


def all_subgroups(table: list[list[int]]) -> dict[Subgroup, list[int]]:
    """Every subgroup with a generating set: cyclic subgroups closed under joins
    with cyclic subgroups until nothing new appears."""
    cyclic: dict[Subgroup, int] = {}
    for g in range(len(table)):
        cyclic.setdefault(closure(table, [g]), g)
    subgroups: dict[Subgroup, list[int]] = {S: [g] for S, g in cyclic.items()}
    frontier = list(subgroups)
    while frontier:
        following = []
        for S in frontier:
            for C, c in cyclic.items():
                if C <= S:
                    continue
                joined = closure(table, subgroups[S] + [c])
                if joined not in subgroups:
                    subgroups[joined] = subgroups[S] + [c]
                    following.append(joined)
        frontier = following
    return subgroups


def conjugate(
    table: list[list[int]], inverses: list[int], S: Subgroup, g: int
) -> Subgroup:
    return frozenset(table[table[g][x]][inverses[g]] for x in S)


def sort_key(S: Subgroup) -> tuple[int, ...]:
    return tuple(sorted(S))


# ---- identification ----------------------------------------------------------------


def rotation_kind(model: Model, rotations: set[Any]) -> tuple[str, int]:
    """``("C", n)``, ``("D", n)``, ``("T", 12)``, ``("O", 24)`` or ``("I", 60)`` for a
    set of rotations forming a subgroup of ``R``."""
    R = model.group.rotation_group
    m = len(rotations)
    orders = [R.order_of(r) for r in rotations]
    if max(orders) == m:
        return ("C", m)
    if m % 2 == 0 and max(orders) == m // 2:
        return ("D", m // 2)
    return {12: ("T", 12), 24: ("O", 24), 60: ("I", 60)}[m]


def identify(model: Model, S: Subgroup) -> str:
    """The normalised Schoenflies symbol of a subgroup, by the family table of
    docs/spec/abstract-groups.md read backwards."""
    G = model.group
    elements = [G.elements[i] for i in S]
    proper = {r for r, p in elements if p == 1}
    improper = {r for r, p in elements if p == -1}
    kind, n = rotation_kind(model, proper)
    if not improper:
        symbol = {"C": f"C{n}", "D": f"D{n}", "T": "T", "O": "O", "I": "I"}[kind]
    elif (G.rotation_group.identity, -1) in elements:
        if kind == "C":
            symbol = f"C{n}h" if n % 2 == 0 else f"S{2 * n}"
        elif kind == "D":
            symbol = f"D{n}h" if n % 2 == 0 else f"D{n}d"
        else:
            symbol = kind + "h"
    else:
        full_kind, full_n = rotation_kind(model, proper | improper)
        if full_kind == "C":
            # R = C_2n' with H = C_n': Cn'h for odd n', S_2n' for even n'
            symbol = f"C{n}h" if n % 2 else f"S{2 * n}"
        elif full_kind == "D" and kind == "C":
            symbol = f"C{full_n}v"
        elif full_kind == "D":
            symbol = f"D{n}h" if n % 2 else f"D{n}d"
        else:
            symbol = "Td"
    return parse_group(symbol).symbol


# ---- the embedding of the library group ---------------------------------------------


def invariant(model: Model, index: int) -> tuple[Any, ...]:
    """The geometric invariant of an element of ``G-dagger``: parity, label kind,
    rotation order, |exponent| and, unless the element is a half turn (whose
    lifted preimage is a convention), whether it is barred."""
    N = model.order
    base, barred = index % N, index >= N
    label = model.labels[base]
    parity = model.group.elements[base][1]
    half_turn = label.kind in (ROTATION, REFLECTION) and label.order == 2
    power = abs(label.power) if label.power is not None else 0
    return (parity, label.kind, label.order, power, None if half_turn else barred)


def element_orders(table: list[list[int]]) -> list[int]:
    orders = []
    for g in range(len(table)):
        k, x = 1, g
        while x != 0:
            x = table[x][g]
            k += 1
        orders.append(k)
    return orders


def generating_set(table: list[list[int]]) -> list[int]:
    """A small generating set of a group given by its Cayley table: elements of
    the highest order first, ties by index, each added only if it is new."""
    orders = element_orders(table)
    generators: list[int] = []
    generated = closure(table, [0])
    for g in sorted(range(1, len(table)), key=lambda g: (-orders[g], g)):
        if g in generated:
            continue
        generators.append(g)
        generated = closure(table, generators)
        if len(generated) == len(table):
            break
    return generators


def extend(
    lib_table: list[list[int]],
    table: list[list[int]],
    generators: list[int],
    images: list[int],
) -> dict[int, int] | None:
    """The homomorphism sending ``generators`` to ``images``, as a map of indices,
    or ``None`` when no such homomorphism exists or it is not injective."""
    phi = {0: 0}
    frontier = [0]
    while frontier:
        following = []
        for x in frontier:
            for g, y in zip(generators, images, strict=True):
                xg, image = lib_table[x][g], table[phi[x]][y]
                if xg in phi:
                    if phi[xg] != image:
                        return None
                else:
                    phi[xg] = image
                    following.append(xg)
        frontier = following
    if len(phi) != len(lib_table) or len(set(phi.values())) != len(phi):
        return None
    return phi


def embed(model: Model, lib: Model, S: Subgroup) -> dict[int, int]:
    """An isomorphism ``H_lib-dagger -> H-dagger`` (indices of ``lib``'s double
    group to indices of ``model``'s double group) preserving the invariants,
    with every generator sent to its admissible image of smallest index."""
    N = model.order
    double = sorted(S) + [i + N for i in sorted(S)]
    targets: dict[tuple[Any, ...], list[int]] = {}
    for i in double:
        targets.setdefault(invariant(model, i), []).append(i)
    lib_table, table = lib.double_table, model.double_table
    generators = generating_set(lib_table)
    candidates = [targets.get(invariant(lib, g), []) for g in generators]
    lib_invariants = [invariant(lib, x) for x in range(len(lib_table))]

    def search(k: int, images: list[int]) -> dict[int, int] | None:
        if k == len(generators):
            phi = extend(lib_table, table, generators, images)
            if phi is None:
                return None
            for x, i in phi.items():
                if lib_invariants[x] != invariant(model, i):
                    return None
            return phi
        for y in candidates[k]:
            if y in images:
                continue
            found = search(k + 1, images + [y])
            if found is not None:
                return found
        return None

    phi = search(0, [])
    if phi is None:
        raise RuntimeError(
            f"no invariant-preserving isomorphism {lib.spec.symbol} -> subgroup of {model.spec.symbol}"
        )
    return phi


# ---- branching --------------------------------------------------------------------


def branching(model: Model, lib: Model, phi: dict[int, int]) -> list[dict[int, int]]:
    """For every irrep of ``G`` the multiplicities of the irreps of ``H`` in its
    restriction: ``(1/|H-dagger|) sum_h chi_G(phi(h)) conj(chi_H(h))``."""
    F = cyclotomic_field(math.lcm(model.conductor, lib.conductor))
    FG, FH = model.field, lib.field
    order = 2 * lib.order
    lifted_H = [
        [F.conjugate(FH.lift(gamma.character(x, lib.order), F)) for x in range(order)]
        for gamma in lib.irreps
    ]
    out = []
    for irrep in model.irreps:
        chi = [FG.lift(irrep.character(phi[x], model.order), F) for x in range(order)]
        row: dict[int, int] = {}
        total_dimension = 0
        for k, gamma in enumerate(lib.irreps):
            value = F.scale(
                F.total(F.mul(a, b) for a, b in zip(chi, lifted_H[k], strict=True)),
                Fraction(1, order),
            )
            if not F.is_rational(value) or value[0].denominator != 1:
                raise RuntimeError(f"non-integral multiplicity {value}")
            m = int(value[0])
            if m:
                row[k] = m
                total_dimension += m * gamma.dimension
        if total_dimension != irrep.dimension:
            raise RuntimeError("the restriction does not exhaust the irrep")
        out.append(row)
    return out


# ---- the catalogue of one group -----------------------------------------------------


@dataclass
class SubgroupClass:
    symbol: str
    members: list[Subgroup]  # conjugates, the representative first
    generators: list[int]  # indices in G of the images of the library generators
    phi: dict[int, int]  # H_lib-dagger index -> G-dagger index
    multiplicities: list[dict[int, int]]  # per irrep of G: {irrep of H: m}
    maximal_in: list[int] = field(default_factory=list)  # classes it is maximal in

    @property
    def representative(self) -> Subgroup:
        return self.members[0]

    @property
    def order(self) -> int:
        return len(self.members[0])

    def max_multiplicity(self, model: Model, projective: bool) -> int:
        return max(
            (
                max(row.values())
                for irrep, row in zip(model.irreps, self.multiplicities, strict=True)
                if irrep.projective == projective
            ),
            default=1,
        )


@dataclass
class Catalogue:
    symbol: str
    model: Model
    classes: list[SubgroupClass]  # proper subgroups, descending order, then by elements

    def class_of(self, S: Subgroup) -> int:
        for k, cls in enumerate(self.classes):
            if S in cls.members:
                return k
        raise KeyError(sorted(S))

    def contains(self, k: int, j: int) -> bool:
        """Some conjugate of class ``j`` lies in the representative of class ``k``."""
        H = self.classes[k].representative
        return any(K <= H for K in self.classes[j].members)


@cache
def catalogue(symbol: str) -> Catalogue:
    model = build_model(parse_group(symbol))
    table, inverses = model.table, model.inverses
    N = model.order
    subgroups = all_subgroups(table)
    seen: set[Subgroup] = set()
    classes: list[SubgroupClass] = []
    for S in sorted(subgroups, key=lambda S: (-len(S), sort_key(S))):
        if S in seen or len(S) == N:
            continue
        orbit = {conjugate(table, inverses, S, g) for g in range(N)}
        seen |= orbit
        members = sorted(orbit, key=sort_key)
        lib = build_model(parse_group(identify(model, members[0])))
        lib_generators = generating_set(lib.double_table)
        # the representative is the conjugate whose generator images (the
        # principal element of H first) have the smallest canonical indices
        embeddings = []
        for member in members:
            phi = embed(model, lib, member)
            images = [phi[g] % N for g in lib_generators if phi[g] % N]
            embeddings.append((images, member, phi))
        embeddings.sort(key=lambda item: item[0])
        generators, representative, phi = embeddings[0]
        members.remove(representative)
        members.insert(0, representative)
        classes.append(
            SubgroupClass(
                lib.spec.symbol, members, generators, phi, branching(model, lib, phi)
            )
        )
    cat = Catalogue(symbol, model, classes)
    for j, cls in enumerate(classes):
        above = [k for k in range(len(classes)) if k != j and cat.contains(k, j)]
        cls.maximal_in = [
            k
            for k in above
            if not any(
                cat.contains(k, i) and cat.contains(i, j) for i in above if i != k
            )
        ]
    return cat


# ---- chains ----------------------------------------------------------------------


@dataclass
class Chain:
    symbols: list[str]  # G first
    subgroups: list[Subgroup]  # as subsets of G, G itself excluded
    generators: list[list[int]]  # per subgroup: generator indices in G
    steps: list[tuple[int, int]]  # per step: max multiplicity (ordinary, projective)

    @property
    def text(self) -> str:
        return " > ".join(self.symbols)

    def canonical(self, projective: bool) -> bool:
        return all(step[1 if projective else 0] == 1 for step in self.steps)

    def abelian_from(self) -> str:
        """The first group of the chain all of whose ordinary irreps are
        one-dimensional (where the chain labels of ordinary irreps are complete)."""
        for symbol in self.symbols:
            model = build_model(parse_group(symbol))
            if all(
                irrep.dimension == 1 for irrep in model.irreps if not irrep.projective
            ):
                return symbol
        raise AssertionError("a chain ends in an abelian group")


def is_terminal(symbol: str) -> bool:
    return parse_group(symbol).family in TERMINAL_FAMILIES


def chains(symbol: str) -> list[Chain]:
    """Every chain from ``symbol`` down to a group with a cyclic rotation group,
    descending through steps that are multiplicity-free for at least one kind
    of irrep and never through the trivial group, up to conjugation in ``G``."""
    cat = catalogue(symbol)
    N = cat.model.order
    table, inverses = cat.model.table, cat.model.inverses
    found: list[Chain] = []

    def walk(top: str, into_G: dict[int, int], chain: Chain) -> None:
        if is_terminal(top) and chain.symbols[1:]:
            found.append(chain)
            return
        sub = catalogue(top)
        for cls in sub.classes:
            if cls.order == 1:
                continue
            step = (
                cls.max_multiplicity(sub.model, False),
                cls.max_multiplicity(sub.model, True),
            )
            if step == (1, 1) or step[0] == 1 or step[1] == 1:
                # compose: lib(H) point index -> top point index -> G index
                lib_order = cls.order
                mapping = {
                    x: into_G[cls.phi[x] % sub.model.order] for x in range(lib_order)
                }
                S = frozenset(mapping.values())
                walk(
                    cls.symbol,
                    mapping,
                    Chain(
                        chain.symbols + [cls.symbol],
                        chain.subgroups + [S],
                        chain.generators + [[into_G[g] for g in cls.generators]],
                        chain.steps + [step],
                    ),
                )

    walk(symbol, {i: i for i in range(N)}, Chain([symbol], [], [], []))
    # reduce to one chain per orbit under simultaneous conjugation by G
    distinct: dict[tuple[tuple[int, ...], ...], Chain] = {}
    for chain in found:
        key = min(
            tuple(sort_key(conjugate(table, inverses, S, g)) for S in chain.subgroups)
            for g in range(N)
        )
        distinct.setdefault(key, chain)
    return list(distinct.values())


# ---- report -----------------------------------------------------------------------


def label_of(model: Model, index: int) -> str:
    return f"{model.labels[index].text}[{index}]"


def decomposition(lib: Model, row: dict[int, int]) -> str:
    parts = []
    for k, m in row.items():
        name = lib.irreps[k].symbol.text
        parts.append(name if m == 1 else f"{m}{name}")
    return " + ".join(parts)


def report_group(symbol: str, out: list[str]) -> None:
    cat = catalogue(symbol)
    model = cat.model
    out.append(f"## {symbol} (order {model.order}, type {model.group.type})")
    out.append("")
    out.append("### Subgroup classes")
    out.append("")
    out.append(
        "| # | H | order | conjugates | generators of the representative (label[index]) | maximal in | ordinary | projective |"
    )
    out.append("|---|---|---|---|---|---|---|---|")
    for k, cls in enumerate(cat.classes):
        gens = ", ".join(label_of(model, g) for g in cls.generators)
        maximal_in = ", ".join(
            "G" if j == -1 else f"#{j}"
            for j in ([-1] if not cls.maximal_in else cls.maximal_in)
        )
        mo = cls.max_multiplicity(model, False)
        mp = cls.max_multiplicity(model, True)
        out.append(
            f"| {k} | {cls.symbol} | {cls.order} | {len(cls.members)} | {gens} | {maximal_in} "
            f"| {'free' if mo == 1 else f'max {mo}'} | {'free' if mp == 1 else f'max {mp}'} |"
        )
    out.append("")
    out.append("### Branching rules")
    out.append("")
    for k, cls in enumerate(cat.classes):
        lib = build_model(parse_group(cls.symbol))
        rules = []
        for irrep, row in zip(model.irreps, cls.multiplicities, strict=True):
            rules.append(f"{irrep.symbol.text} -> {decomposition(lib, row)}")
        out.append(f"- #{k} {symbol} > {cls.symbol}: " + "; ".join(rules))
    out.append("")
    all_chains = chains(symbol)
    out.append("### Chains")
    out.append("")
    out.append(
        "Chains down to a group with a cyclic rotation group through steps that are "
        "multiplicity-free for at least one kind of irrep, one per conjugacy class of "
        "chains (simultaneous conjugation in G). `abelian from` is the first group "
        "of the chain whose ordinary irreps are all one-dimensional. The last column "
        "names every subgroup of the chain by the canonical elements of G that "
        "generate it."
    )
    out.append("")
    out.append("| chain | ordinary | projective | both | abelian from | subgroups |")
    out.append("|---|---|---|---|---|---|")
    for chain in sorted(all_chains, key=lambda c: (len(c.symbols), c.text)):
        ordinary, projective = chain.canonical(False), chain.canonical(True)
        gens = " > ".join(
            "{" + ", ".join(label_of(model, g) for g in generators) + "}"
            for generators in chain.generators
        )
        out.append(
            f"| {chain.text} | {'yes' if ordinary else 'no'} | {'yes' if projective else 'no'} "
            f"| {'yes' if ordinary and projective else 'no'} | {chain.abelian_from()} | {gens} |"
        )
    by_text: dict[str, list[Chain]] = {}
    for chain in all_chains:
        by_text.setdefault(chain.text, []).append(chain)
    ambiguous = {t: cs for t, cs in by_text.items() if len(cs) > 1}
    if ambiguous:
        out.append("")
        out.append(
            "Chains whose symbol string names more than one conjugacy class of chains:"
        )
        for text, cs in sorted(ambiguous.items()):
            kinds = sorted(
                {
                    f"ordinary={c.canonical(False)}, projective={c.canonical(True)}"
                    for c in cs
                }
            )
            out.append(f"- {text}: {len(cs)} classes ({'; '.join(kinds)})")
    out.append("")


def summary_table(symbols: list[str], out: list[str]) -> None:
    """One row per group: the steps G > H and their multiplicity-free status."""
    out.append("## Summary of single steps")
    out.append("")
    out.append("| G | H (conjugates) | ordinary | projective |")
    out.append("|---|---|---|---|")
    for symbol in symbols:
        cat = catalogue(symbol)
        for cls in cat.classes:
            if cls.order == 1:
                continue
            mo = cls.max_multiplicity(cat.model, False)
            mp = cls.max_multiplicity(cat.model, True)
            out.append(
                f"| {symbol} | {cls.symbol} ({len(cls.members)}) | {mo} | {mp} |"
            )
    out.append("")


def default_symbols(max_n: int) -> list[str]:
    symbols = []
    for family in AXIAL_FAMILIES:
        for n in range(1, max_n + 1):
            head, tail = family[0], family[-1] if family[-1] in "vhd" else ""
            subscript = 2 * n if family == "S2n" else n
            symbols.append(parse_group(f"{head}{subscript}{tail}").symbol)
    symbols.extend(POLYHEDRAL)
    seen: set[str] = set()
    return [s for s in symbols if not (s in seen or seen.add(s))]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--max-n", type=int, default=12)
    parser.add_argument("--groups", nargs="*")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--summary", action="store_true", help="single-step table only")
    args = parser.parse_args(argv)
    symbols = (
        [parse_group(s).symbol for s in args.groups]
        if args.groups
        else default_symbols(args.max_n)
    )
    out: list[str] = [
        "# Subgroup catalogue (generated)",
        "",
        (
            "Generated by `docs/research/scripts/subgroup_chains.py`; do not edit. "
            "Element indices are the canonical indices of the `elements` table of G; "
            "`free` means multiplicity-free."
        ),
        "",
    ]
    if args.summary:
        summary_table(symbols, out)
    else:
        for symbol in symbols:
            report_group(symbol, out)
            print(f"{symbol}: done", file=sys.stderr)
    text = "\n".join(out) + "\n"
    if args.out:
        args.out.write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
