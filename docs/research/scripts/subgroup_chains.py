"""Subgroup catalogue and canonical group chains of every point-group family.

Research script of ticket #41 (docs/research/subgroup-chains.md). For every
group of the catalogue (the axial families at ``n = 1..12`` and the seven
polyhedral groups) it computes, with the library only:

1. the subgroups of the abstract group up to conjugacy, each identified as a
   point group of the same families (family and axis order read off the
   rotation parts and the parity), the number of conjugates, the canonical
   elements (labels and indices) that generate the representative, and the
   maximal-subgroup lattice;
2. the branching (restriction) multiplicities of every ordinary and projective
   irrep of ``G`` into the irreps of every subgroup ``H``, and whether the
   step ``G > H`` is multiplicity-free for the ordinary irreps, for the
   projective irreps and for both;
3. every group chain ``G > H > ... > K`` that descends through canonical steps
   to a group whose rotation group is cyclic (``Cn``, ``Cnh``, ``S2n``), up to
   simultaneous conjugation in ``G``, with the kind of irreps for which the
   chain is canonical.

Method. Subgroups are enumerated from the Cayley table by closing cyclic
subgroups under joins; conjugates by conjugating element sets. A subgroup
``H`` is matched to the library's point group of the same symbol by an
explicit isomorphism of double groups ``H_lib-dagger -> H-dagger`` (the
preimage of ``H`` in ``G-dagger``) that preserves parity, the geometric
invariants of every element (label kind, rotation order and |exponent|) and,
for every element that is not a half turn, which preimage is the lifted one.
The generators of ``H_lib-dagger`` are sent to the candidates of smallest
canonical index, so the embedding is deterministic: the principal element of
``H`` is the admissible element of ``G`` with the smallest index. Branching
multiplicities are inner products over ``H-dagger`` of the restricted
character of ``G`` with the characters of ``H_lib``, computed exactly in the
cyclotomic field of the larger conductor.

Usage::

    uv run python3 docs/research/scripts/subgroup_chains.py [--max-n 12]
        [--groups D6h Oh ...] [--out docs/research/subgroup-chains-catalogue.md]

Without ``--out`` the catalogue is printed to standard output.
"""

