"""Finite rotation groups as exact integer objects (docs/spec/abstract-groups.md).

``Cn``: residues mod ``n``. ``Dn``: pairs ``(k mod n, s)`` meaning ``C_n^k (C2')^s``.
``T``, ``O``, ``I``: permutations of 4, 4, 5 points, generated by breadth-first
closure from fixed generators and sorted into the canonical order.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

Perm = tuple[int, ...]


@dataclass(frozen=True)
class RotationGroup:
    """A rotation group ``R``: elements in canonical order, ``elements[0]`` the identity."""

    name: str
    elements: tuple[Any, ...]
    mul: Callable[[Any, Any], Any]
    inv: Callable[[Any], Any]
    axis_order: int | None  # N of C_N or D_N; None for T, O, I

    @property
    def polyhedral(self) -> bool:
        return self.axis_order is None

    @property
    def identity(self) -> Any:
        return self.elements[0]

    def order_of(self, r: Any) -> int:
        return element_order(self.mul, self.identity, r)


def element_order(mul: Callable[[Any, Any], Any], identity: Any, r: Any) -> int:
    """The smallest ``n >= 1`` with ``r^n`` the identity."""
    n, q = 1, r
    while q != identity:
        q = mul(q, r)
        n += 1
    return n


def cyclic(n: int) -> RotationGroup:
    return RotationGroup(
        name=f"C{n}",
        elements=tuple(range(n)),
        mul=lambda a, b: (a + b) % n,
        inv=lambda a: (-a) % n,
        axis_order=n,
    )


def dihedral(n: int) -> RotationGroup:
    def mul(a: tuple[int, int], b: tuple[int, int]) -> tuple[int, int]:
        k1, s1 = a
        k2, s2 = b
        return ((k1 + (k2 if s1 == 0 else -k2)) % n, (s1 + s2) % 2)

    def inv(a: tuple[int, int]) -> tuple[int, int]:
        k, s = a
        return ((-k) % n if s == 0 else k, s)

    elements = tuple((k, 0) for k in range(n)) + tuple((k, 1) for k in range(n))
    return RotationGroup(
        name=f"D{n}", elements=elements, mul=mul, inv=inv, axis_order=n
    )


def perm_mul(p: Perm, q: Perm) -> Perm:
    """``(p q)(x) = p(q(x))``: apply ``q`` first, then ``p``."""
    return tuple(p[q[x]] for x in range(len(p)))


def perm_inv(p: Perm) -> Perm:
    out = [0] * len(p)
    for i, j in enumerate(p):
        out[j] = i
    return tuple(out)


def perm_even(p: Perm) -> bool:
    inversions = sum(
        1 for i in range(len(p)) for j in range(i + 1, len(p)) if p[i] > p[j]
    )
    return inversions % 2 == 0


_GENERATORS: dict[str, tuple[list[Perm], int]] = {
    "T": ([(1, 2, 0, 3), (1, 0, 3, 2)], 4),
    "O": ([(1, 2, 3, 0), (1, 0, 2, 3)], 4),
    "I": ([(1, 2, 3, 4, 0), (1, 2, 0, 3, 4)], 5),
}


def _closure(generators: list[Perm], degree: int) -> list[Perm]:
    """Breadth-first closure: a deterministic enumeration of the generated group."""
    identity = tuple(range(degree))
    elements = [identity]
    seen = {identity}
    frontier = [identity]
    while frontier:
        following = []
        for g in frontier:
            for h in generators:
                gh = perm_mul(g, h)
                if gh not in seen:
                    seen.add(gh)
                    elements.append(gh)
                    following.append(gh)
        frontier = following
    return elements


def polyhedral(name: str) -> RotationGroup:
    """``T``, ``O`` or ``I`` in the canonical order of the abstract-groups chapter."""
    generators, degree = _GENERATORS[name]
    closure = _closure(generators, degree)
    identity = closure[0]
    bfs_index = {p: i for i, p in enumerate(closure)}

    def order_of(p: Perm) -> int:
        return element_order(perm_mul, identity, p)

    def conjugacy_class(p: Perm) -> frozenset[Perm]:
        return frozenset(perm_mul(perm_mul(h, p), perm_inv(h)) for h in closure)

    # ascending rotation order, then class (size, then smallest breadth-first
    # index in the class), then breadth-first index: classes come out contiguous
    def key(p: Perm) -> tuple[int, int, int, int]:
        cls = conjugacy_class(p)
        return (order_of(p), len(cls), min(bfs_index[x] for x in cls), bfs_index[p])

    elements = tuple(sorted(closure, key=key))
    return RotationGroup(
        name=name, elements=elements, mul=perm_mul, inv=perm_inv, axis_order=None
    )
