from dataclasses import dataclass

# --------------------------------------------------------------------------
# Rotation groups R (abstract, exact)
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class RotationGroup:
    name: str
    elements: tuple  # canonical order, elements[0] is the identity
    mul: Callable
    inv: Callable

    def index(self, r):
        return self.elements.index(r)


def cyclic(n: int) -> RotationGroup:
    return RotationGroup(
        name=f"C{n}",
        elements=tuple(range(n)),
        mul=lambda a, b: (a + b) % n,
        inv=lambda a: (-a) % n,
    )


def dihedral(n: int) -> RotationGroup:
    # (k, s): C_n^k followed by (C2')^s; C2' inverts the rotation exponent.
    def mul(a, b):
        k1, s1 = a
        k2, s2 = b
        return ((k1 + (k2 if s1 == 0 else -k2)) % n, (s1 + s2) % 2)

    def inv(a):
        k, s = a
        return ((-k) % n if s == 0 else k, s)

    elements = tuple((k, 0) for k in range(n)) + tuple((k, 1) for k in range(n))
    return RotationGroup(name=f"D{n}", elements=elements, mul=mul, inv=inv)


def _perm_mul(p, q):
    # (p*q)(x) = p(q(x)): apply q first, then p
    return tuple(p[q[x]] for x in range(len(p)))


def _perm_inv(p):
    out = [0] * len(p)
    for i, j in enumerate(p):
        out[j] = i
    return tuple(out)


def _closure(generators, degree):
    ident = tuple(range(degree))
    elements = [ident]
    seen = {ident}
    frontier = [ident]
    while frontier:  # breadth-first closure: deterministic order
        nxt = []
        for g in frontier:
            for h in generators:
                gh = _perm_mul(g, h)
                if gh not in seen:
                    seen.add(gh)
                    elements.append(gh)
                    nxt.append(gh)
        frontier = nxt
    return tuple(elements)


def polyhedral(kind: str) -> RotationGroup:
    if kind == "T":  # A4 on 4 vertices of the tetrahedron
        gens, deg = [(1, 2, 0, 3), (1, 0, 3, 2)], 4
    elif kind == "O":  # S4 on the 4 body diagonals of the cube
        gens, deg = [(1, 2, 3, 0), (1, 0, 2, 3)], 4
    elif kind == "I":  # A5 on 5 inscribed cubes of the dodecahedron
        gens, deg = [(1, 2, 3, 4, 0), (1, 2, 0, 3, 4)], 5
    else:
        raise ValueError(kind)
    closure = _closure(gens, deg)
    ident = closure[0]

    def order_of(p):
        n, q = 1, p
        while q != ident:
            q = _perm_mul(q, p)
            n += 1
        return n

    # Canonical order (ticket #2, Q2 = b, Q6 = b): by rotation order
    # ascending, then conjugacy class (class size ascending, then smallest
    # breadth-first index in the class), then breadth-first closure index.
    # Coordinate-free and stable.
    def conj_class(p):
        return frozenset(_perm_mul(_perm_mul(h, p), _perm_inv(h)) for h in closure)

    def key(p):
        c = conj_class(p)
        return (order_of(p), len(c), min(closure.index(x) for x in c), closure.index(p))

    elements = tuple(sorted(closure, key=key))
    return RotationGroup(name=kind, elements=elements, mul=_perm_mul, inv=_perm_inv)


# --------------------------------------------------------------------------
# Point groups G  <=  R x {+1, -1}
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class PointGroup:
    symbol: str
    rotation_group: RotationGroup
    kind: str  # "proper" | "centro" | "twisted"
    elements: tuple  # of (r, parity), canonical order

    @property
    def order(self):
        return len(self.elements)

    def mul(self, a, b):
        R = self.rotation_group
        return (R.mul(a[0], b[0]), a[1] * b[1])

    def inv(self, a):
        return (self.rotation_group.inv(a[0]), a[1])

    def identity(self):
        return self.elements[0]

    def cayley(self):
        idx = {g: i for i, g in enumerate(self.elements)}
        return [[idx[self.mul(a, b)] for b in self.elements] for a in self.elements]


def proper(symbol, R):
    return PointGroup(symbol, R, "proper", tuple((r, +1) for r in R.elements))


def centro(symbol, R):
    els = tuple((r, +1) for r in R.elements) + tuple((r, -1) for r in R.elements)
    return PointGroup(symbol, R, "centro", els)


def twisted(symbol, R, in_H):
    """G = {(r, +1) : r in H} u {(r, -1) : r not in H}, H an index-2 subgroup."""
    els = tuple((r, +1) for r in R.elements if in_H(r)) + tuple(
        (r, -1) for r in R.elements if not in_H(r)
    )
    return PointGroup(symbol, R, "twisted", els)


def even_k(r):  # index-2 subgroup {k even} of C_2n or D_2n
    k = r if isinstance(r, int) else r[0]
    return k % 2 == 0


def no_flip(r):  # index-2 subgroup C_n of D_n
    return r[1] == 0


def even_perm(p):  # index-2 subgroup A4 = T of S4 = O
    inv = 0
    for i in range(len(p)):
        for j in range(i + 1, len(p)):
            if p[i] > p[j]:
                inv += 1
    return inv % 2 == 0


ALIASES = {
    "Cs": "C1h",
    "Ci": "S2",
    "C1v": "C1h",
    "D1": "C2",
    "D1h": "C2v",
    "D1d": "C2h",
    "V": "D2",
    "Vh": "D2h",
    "Vd": "D2d",
}


def parse(symbol: str):
    symbol = ALIASES.get(symbol, symbol)
    if symbol in ("T", "Td", "Th", "O", "Oh", "I", "Ih"):
        return symbol, None
    head = symbol[0]
    rest = symbol[1:]
    digits = "".join(ch for ch in rest if ch.isdigit())
    suffix = rest[len(digits) :]
    if head not in "CDS" or not digits:
        raise ValueError(f"not a Schoenflies symbol: {symbol}")
    return head + suffix, int(digits)


def point_group(symbol: str) -> PointGroup:
    family, n = parse(symbol)
    if family == "C":
        return proper(symbol, cyclic(n))
    if family == "Cv":
        return twisted(symbol, dihedral(n), no_flip)
    if family == "Ch":
        return centro(symbol, cyclic(n)) if n % 2 == 0 else twisted(symbol, cyclic(2 * n), even_k)
    if family == "S":
        if n % 2:
            raise ValueError("S_n needs even n (S2n)")
        m = n // 2
        return centro(symbol, cyclic(m)) if m % 2 else twisted(symbol, cyclic(n), even_k)
    if family == "D":
        return proper(symbol, dihedral(n))
    if family == "Dh":
        return centro(symbol, dihedral(n)) if n % 2 == 0 else twisted(symbol, dihedral(2 * n), even_k)
    if family == "Dd":
        return centro(symbol, dihedral(n)) if n % 2 else twisted(symbol, dihedral(2 * n), even_k)
    if family == "T":
        return proper(symbol, polyhedral("T"))
    if family == "Td":
        return twisted(symbol, polyhedral("O"), even_perm)
    if family == "Th":
        return centro(symbol, polyhedral("T"))
    if family == "O":
        return proper(symbol, polyhedral("O"))
    if family == "Oh":
        return centro(symbol, polyhedral("O"))
    if family == "I":
        return proper(symbol, polyhedral("I"))
    if family == "Ih":
        return centro(symbol, polyhedral("I"))
    raise ValueError(f"unknown family {family}")


