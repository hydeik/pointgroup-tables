"""PROTOTYPE - THROWAWAY. Not part of the package.

Question (wayfinder ticket #2, "Abstract group construction for every
point-group family"):

    Can every finite point group be built as an *abstract* group, with no
    coordinate system and no floating point, from a uniform recipe that also
    remembers which elements are proper (det = +1) and which are improper
    (det = -1)?  Does the resulting element enumeration and Cayley table
    feel right as the core data model of the CLI?

Model under test (classical Type I / II / III classification):

    A point group G is a subgroup of R x {+1, -1}, where R is a finite
    rotation group (Cn, Dn, T, O or I) handled abstractly:

      * proper   (Type I):   G = { (r, +1) : r in R }                 e.g. Dn, O
      * centro   (Type II):  G = R x {+1, -1}                          e.g. D6h, Oh
      * twisted  (Type III): G = { (r, chi(r)) : r in R }, chi = +1 on an
                             index-2 subgroup H of R, -1 elsewhere      e.g. C3v, Td

    Rotation groups are exact integer objects:

      * Cn : k mod n
      * Dn : (k mod n, s in {0,1})  with  C2' C^k C2' = C^-k
      * T, O, I : permutation groups A4, S4, A5 generated by closure

    An element of G is the pair (r, parity).  Canonical order: proper
    elements first (in R order), then improper elements (in R order).
    R order: Cn and Dn by (k, s); T, O, I by rotation order ascending, then
    conjugacy class (size ascending), then breadth-first closure index
    (decided: ticket #2, Q2 = b and Q6 = b).

Run:  uv run python prototypes/abstract_group_prototype.py [C3v D2d Oh ...]
      (no arguments: run a self-check over many groups)
"""

from __future__ import annotations

