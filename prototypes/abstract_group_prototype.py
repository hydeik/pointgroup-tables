def check_axioms(G: PointGroup):
    els = G.elements
    idx = {g: i for i, g in enumerate(els)}
    e = G.identity()
    assert all(G.mul(e, g) == g and G.mul(g, e) == g for g in els), "identity"
    assert all(G.mul(g, G.inv(g)) == e for g in els), "inverse"
    assert all(G.mul(a, b) in idx for a in els for b in els), "closure"
    if G.order <= 48:
        assert all(
            G.mul(G.mul(a, b), c) == G.mul(a, G.mul(b, c))
            for a in els
            for b in els
            for c in els
        ), "associativity"


def element_order(G, g):
    n, h = 1, g
    while h != G.identity():
        h = G.mul(h, g)
        n += 1
    return n


def conjugacy_classes(G):
    remaining = list(G.elements)
    classes = []
    while remaining:
        g = remaining[0]
        cls = {G.mul(G.mul(h, g), G.inv(h)) for h in G.elements}
        classes.append(sorted(cls, key=G.elements.index))
        remaining = [x for x in remaining if x not in cls]
    return classes


def invariants(G):
    return {
        "order": G.order,
        "proper": sum(1 for _, p in G.elements if p == +1),
        "has_inversion": (G.identity()[0], -1) in G.elements,
        "abelian": all(G.mul(a, b) == G.mul(b, a) for a in G.elements for b in G.elements),
        "classes": len(conjugacy_classes(G)),
        "orders": dict(sorted(Counter(element_order(G, g) for g in G.elements).items())),
    }


