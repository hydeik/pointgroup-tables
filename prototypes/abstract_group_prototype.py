def generic_label(G, g):
    """Coordinate-free placeholder label: R-element + parity; a label
    convention would replace this."""
    r, p = g
    R = G.rotation_group
    core = f"{R.name}[{R.index(r)}]"
    return core if p == +1 else core + "*"


def show(symbol):
    G = point_group(symbol)
    check_axioms(G)
    inv = invariants(G)
    print(f"== {symbol}: R = {G.rotation_group.name}, kind = {G.kind}")
    print("   invariants:", inv)
    labels = [generic_label(G, g) for g in G.elements]
    print("   elements  :", " ".join(labels))
    if G.order <= 12:
        print("   Cayley table (row * column -> index):")
        for row in G.cayley():
            print("     ", " ".join(f"{x:2d}" for x in row))
    classes = conjugacy_classes(G)
    print("   classes   :", [[generic_label(G, g) for g in c] for c in classes])
    print()


def selfcheck():
    bad = 0
    for sym, (order, ncls) in KNOWN.items():
        G = point_group(sym)
        check_axioms(G)
        inv = invariants(G)
        ok = (inv["order"], inv["classes"]) == (order, ncls)
        bad += not ok
        flag = "ok " if ok else "BAD"
        print(f"{flag} {sym:5s} order={inv['order']:4d} classes={inv['classes']:3d} "
              f"expected=({order},{ncls}) R={G.rotation_group.name} {G.kind}")
    print(f"\n{len(KNOWN) - bad}/{len(KNOWN)} groups match (order, #classes).")


